const TABLES: Record<Lang, Table> = { en: en as unknown as Table, ru, uk };
let lang: Lang = 'en';

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return lang;
}

export function isLang(v: unknown): v is Lang {
  return v === 'en' || v === 'ru' || v === 'uk';
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = TABLES[lang][key] ?? TABLES.en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Translated text for a notation parse error. */
export function notationError(e: { code: string; arg?: string }): string {
  const key = `err.${e.code}` as Key;
  return t(key, { a: e.arg ?? '' });
}

export function tag(): Lang {
  return lang;
}
